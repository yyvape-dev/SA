// 2026-11-02 改稿。章の台本と表示を分離。/ は画面内の改行。
export function D(text) {
  return text.trim().split('\n').map(line => {
    const at = line.indexOf('|');
    if (at < 1) throw new Error('台本の話者がありません: ' + line);
    return [line.slice(0, at).trim(), line.slice(at + 1).trim().replaceAll('/', '\n')];
  });
}
